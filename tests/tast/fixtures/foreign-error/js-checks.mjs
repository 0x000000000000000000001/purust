import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
const P = await import(pathToFileURL(`${process.argv[2]}/ForeignProbe/index.js`));
const O = await import(pathToFileURL(`${process.argv[2]}/Data.Ordering/index.js`));
const m = s => P.message(s), idx = (i, e) => P.atIndex(i)(e), prop = (p, e) => P.atProperty(p)(e);
const four = [m('bad'), P.mismatch('String')('Number'), idx(2, m('bad')), prop('é🙂', m('bad'))];
assert.deepEqual(four.map(P.tag), [0, 1, 2, 3]);
assert.deepEqual(four.map(P.render), ['bad', 'Type mismatch: expected String, found Number', 'Error at array index 2: bad', 'Error at property "é🙂": bad']);
assert.equal(P.render(prop('item', idx(-1, P.mismatch('X')('Y')))), 'Error at property "item": Error at array index -1: Type mismatch: expected X, found Y');
assert.deepEqual(four.map(P.display), ['(ForeignError "bad")', '(TypeMismatch "String" "Number")', '(ErrorAtIndex 2 (ForeignError "bad"))', '(ErrorAtProperty "é🙂" (ForeignError "bad"))']);
for (let i = 0; i < 4; i++) for (let j = 0; j < 4; j++) assert.equal(P.equal(four[i])(four[j]), i === j);
assert.equal(P.equal(prop('x', idx(2, m('a'))))(prop('x', idx(2, m('b')))), false);
for (let i = 0; i < 4; i++) for (let j = 0; j < 4; j++) assert.equal(P.order(four[i])(four[j]).constructor, (i < j ? O.LT : i > j ? O.GT : O.EQ));
assert.equal(P.order(idx(1, m('z')))(idx(2, m('a'))).constructor, O.LT);
assert.equal(P.order(prop('x', m('a')))(prop('x', m('b'))).constructor, O.LT);
assert.equal(P.equal(P.polymorphic(four[3]))(four[3]), true);
assert.equal(P.render(P.throughCallback(P.message)('callback')), 'callback');
for (const x of [-2147483648, 0, 2147483647]) assert.equal(P.roundInt(x), x);
for (const x of ['', 'é🙂']) assert.equal(P.roundString(x), x);
for (const x of [1, 'x', null, undefined, [1], { handle: 42 }]) assert.equal(P.carrier(x), x);
console.log('JS: 10 contract groups passed');
