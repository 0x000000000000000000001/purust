import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
const P = await import(pathToFileURL(`${process.argv[2]}/VariantPublicProbe/index.js`));
const O = await import(pathToFileURL(`${process.argv[2]}/Data.Ordering/index.js`));
assert.deepEqual(P.integer(7), { type: 'integer', value: 7 });
assert.deepEqual(P.text('é🙂'), { type: 'text', value: 'é🙂' });
assert.equal(P.project(P.integer(-5)), -5); assert.equal(P.project(P.text('x')), -999);
assert.equal(P.describe(P.integer(7)), 'int:7'); assert.equal(P.describe(P.text('é🙂')), 'text:é🙂');
assert.equal(P.onlyInteger(n => `callback:${n}`)(P.integer(8)), 'callback:8');
assert.equal(P.onlyInteger(() => { throw Error('must skip'); })(P.text('x')), 'skip');
assert.equal(P.project(P.increment(P.integer(7))), 8); assert.equal(P.describe(P.increment(P.text('x'))), 'text:x');
assert.equal(P.project(P.expanded(9)), 9);
assert.equal(P.contracted(P.integer(9)), 9); assert.equal(P.contracted(P.text('x')), -999);
assert.equal(P.equal(P.integer(1))(P.integer(1)), true); assert.equal(P.equal(P.integer(1))(P.integer(2)), false);
assert.equal(P.equal(P.integer(1))(P.text('1')), false); assert.equal(P.equal(P.text('é🙂'))(P.text('é🙂')), true);
assert.equal(P.order(P.integer(1))(P.integer(2)).constructor, O.LT); assert.equal(P.order(P.text('b'))(P.text('a')).constructor, O.GT);
assert.equal(P.order(P.integer(99))(P.text('0')).constructor, O.LT); assert.equal(P.order(P.text('same'))(P.text('same')).constructor, O.EQ);
assert.equal(P.display(P.integer(7)), '(inj @"integer" 7)'); assert.equal(P.display(P.text('é🙂')), '(inj @"text" "é🙂")');
for (const x of [P.integer(7), P.text('é🙂')]) assert.deepEqual(P.roundtrip(x), x);
for (const x of [42, 'é🙂', [1], { handle: 2 }, () => 'ok']) assert.equal(P.generic(x).value, x);
assert.throws(() => P.rejectUnknown(undefined), /Data.Variant: pattern match failure \[missing\]/);
