import { readFileSync, writeFileSync } from 'node:fs';
import { runtime as records } from '../src/Purust/RecordFields.js';
import { runtime as arrays } from '../src/Purust/NativeArrays.js';
import { runtime as values } from '../src/Purust/ModuleValues.js';
import { runtimeHelpers } from '../src/Purust/Utf16.js';

// Both compilers embed the same canonical bytes. No source checkout is needed
// when the native compiler subsequently writes an application's runtime.
const root = new URL('../', import.meta.url);
const header = '// Generated by tools/embed-native-runtime.mjs.\n';
const read = path => readFileSync(new URL(path, root), 'utf8');
function literal(text) {
  let hashes = '#';
  while (text.includes(`"${hashes}`)) hashes += '#';
  return `r${hashes}"${text}"${hashes}`;
}
function write(module, source) {
  const path = new URL(`src/Purust/${module}.rs`, root);
  let previous;
  try { previous = readFileSync(path, 'utf8'); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (previous !== source) writeFileSync(path, source);
}
for (const [module, source] of [['RecordFields', records], ['NativeArrays', arrays], ['ModuleValues', values]]) {
  write(module, header + `pub fn Purust_${module}_runtime() -> String {\n    purust_string_from_utf8(${literal(source)})\n}\n`);
}
const files = ['Cargo.toml', 'src/lib.rs', 'src/local.rs', 'src/threaded.rs'];
write('Runtime', header + `
pub fn Purust_Runtime_microtasksSource() -> String {
    purust_string_from_utf8(${literal(read('src/Purust/Microtasks.rs'))})
}

pub fn Purust_Runtime_runtimeFiles() -> Value {
    mk_array(vec![
${files.map(path => `        (${literal(path)}, ${literal(read(`tests/runtime/perceus_ptr/${path}`))}),`).join('\n')}
    ].into_iter().map(|(path, content)| {
        let mut fields = RecordFields::new();
        fields.insert("path".into(), Value::String(purust_string_from_utf8(path)));
        fields.insert("content".into(), Value::String(purust_string_from_utf8(content)));
        Value::DynamicRecord(perceus_ptr::PerceusPtr::new(fields))
    }).collect())
}
`);
write('Utf16', header + `
fn purust_escape_scalar(value: char) -> String {
    match value {
        '"' => "\\\\\\\"".into(),
        '\\'' => "\\\\'".into(),
        '\\\\' => "\\\\\\\\".into(),
        ' '..='~' => value.to_string(),
        _ => format!("\\\\u{{{:x}}}", value as u32),
    }
}

pub fn Purust_Utf16_rustStrLiteral(value: String) -> String {
    format!("\\\"{}\\\"", value.chars().map(purust_escape_scalar).collect::<String>())
}

pub fn Purust_Utf16_rustStringLiteral(value: String) -> String {
    format!("String::from({})", Purust_Utf16_rustStrLiteral(value))
}

pub fn Purust_Utf16_rustCharLiteral(value: char) -> String {
    format!("'{}'", purust_escape_scalar(value))
}

pub fn Purust_Utf16_runtimeHelpers() -> String {
    purust_string_from_utf8(${literal(runtimeHelpers)})
}
`);
